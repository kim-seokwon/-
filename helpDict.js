//  찾기 — 화면 이름·3줄·낱말·그 화면 숫자 설명(TIPS 원문)까지. 공백으로 나눈 낱말이 모두 들어 있어야 맞는다.
export function searchManual(q, manual = MANUAL, tips = TIPS) {
    const words = String(q || '').toLowerCase().split(/\s+/).filter(Boolean);
    if (!words.length) return manual.slice();
    return manual.filter(m => {
        const hay = [m.title, ...m.lines, ...m.keywords, ...m.tips.flatMap(k => tips[k] ? [tips[k].title, ...tips[k].lines] : [])]
            .join(' ').toLowerCase();
        return words.every(w => hay.includes(w));
    });
}
